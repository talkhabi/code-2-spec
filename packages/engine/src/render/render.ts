import { mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import type { Project } from '../project.js';
import { getEvidence, listItems, listPhases, listRelations, type Item, type Phase } from '../specs/store.js';
import { computeCoverage } from '../graph/coverage.js';
import type { Evidence, Scenario } from '../ai/schemas.js';

const VARIANT_ORDER = ['happy', 'alternate', 'error', 'edge'];

function write(file: string, content: string) {
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, content.replace(/\n{3,}/g, '\n\n'));
}

const visible = (i: Item) => i.status !== 'rejected';

export function evidenceLine(e: Evidence) {
  const lines = e.startLine ? `:${e.startLine}${e.endLine && e.endLine !== e.startLine ? `-${e.endLine}` : ''}` : '';
  return `\`${e.file}${lines}\`${e.symbol ? ` (${e.symbol})` : ''}${e.note ? ` — ${e.note}` : ''}`;
}

function evidenceBlock(project: Project, id: string) {
  const ev = getEvidence(project, id);
  return ev.length ? `<details><summary>Legacy evidence (${ev.length})</summary>\n\n${ev.map((e) => `- ${evidenceLine(e)}`).join('\n')}\n\n</details>\n` : '';
}

function statusBadge(i: Item) {
  return i.status === 'approved' ? '✅ approved' : i.status === 'edited' ? '✏️ edited' : '⏳ pending review';
}

export function mermaidLabel(s: string) {
  return s.replace(/["`]/g, "'").replace(/[<>{}[\]|]/g, ' ').slice(0, 80);
}

export function flowMermaid(flow: Item) {
  const steps: { layer: string; description: string }[] = flow.data.steps ?? [];
  const lines = ['flowchart LR'];
  steps.forEach((s, i) => {
    lines.push(`  s${i}["${mermaidLabel(`${s.layer}: ${s.description}`)}"]`);
    if (i > 0) lines.push(`  s${i - 1} --> s${i}`);
  });
  return lines.join('\n');
}

export function renderGherkin(feature: Item, journeys: Item[]): string {
  const out = [`Feature: ${feature.title}`, ...(feature.summary ? feature.summary.split('\n').map((l) => `  ${l}`) : []), ''];
  for (const j of journeys) {
    out.push(`  # Journey: ${j.title} [${j.data.variant}] — actor: ${j.data.actor}`);
    for (const sc of (j.data.scenarios ?? []) as Scenario[]) {
      const tags = [`@${j.data.variant}`, `@journey-${j.slug}`, ...(sc.tags ?? []).map((t) => (t.startsWith('@') ? t : `@${t}`))];
      out.push(`  ${tags.join(' ')}`);
      out.push(`  ${sc.examples ? 'Scenario Outline' : 'Scenario'}: ${sc.name}`);
      const kw = (k: string, steps: string[]) => steps.forEach((s, i) => out.push(`    ${i === 0 ? k : 'And'} ${s.replace(/^(Given|When|Then|And|But)\s+/i, '')}`));
      kw('Given', sc.given);
      kw('When', sc.when);
      kw('Then', sc.then);
      if (sc.examples) {
        out.push('', '    Examples:');
        out.push(`      | ${sc.examples.headers.join(' | ')} |`);
        for (const row of sc.examples.rows) out.push(`      | ${row.join(' | ')} |`);
      }
      out.push('');
    }
  }
  return out.join('\n');
}

export function renderPlaywright(feature: Item, journeys: Item[]): string {
  const out = [
    `// Generated by code2spec from legacy behaviour. Feature: ${feature.title}`,
    `// Run against the legacy app and the rebuild: BASE_URL=http://localhost:5173 npx playwright test`,
    `import { test, expect } from '@playwright/test';`,
    '',
    `test.describe(${JSON.stringify(feature.title)}, () => {`,
  ];
  for (const j of journeys) {
    const body: string | undefined = j.data.playwright;
    const name = JSON.stringify(`[${j.data.variant}] ${j.title}`);
    if (body?.trim()) {
      const inner = body.trim().replace(/^test\([\s\S]*?async\s*\(\{\s*page\s*\}\)\s*=>\s*\{\n?/, '').replace(/\}\);?\s*$/, '');
      out.push(`  test(${name}, async ({ page }) => {`, ...inner.split('\n').map((l) => `    ${l.trimEnd()}`), '  });', '');
    } else {
      out.push(`  test.fixme(${name}, async ({ page }) => {`, `    // TODO: implement from the Gherkin scenarios of journey "${j.slug}"`, '  });', '');
    }
  }
  out.push('});', '');
  return out.join('\n').replace(/^\s+$/gm, '');
}

function renderJourney(project: Project, j: Item) {
  const d = j.data;
  const steps = (d.steps ?? []).map((s: any, i: number) => `${i + 1}. **${s.actor === 'user' ? 'User' : 'System'}:** ${s.action}${s.expected ? ` → _${s.expected}_` : ''}`);
  return [
    `### ${j.title}`,
    `\`${d.variant}\` · actor: **${d.actor}** · confidence: ${j.confidence != null ? Math.round(j.confidence * 100) + '%' : '–'} · ${statusBadge(j)} · id: \`${j.id}\``,
    '',
    `**Goal:** ${d.goal ?? j.summary ?? ''}`,
    d.trigger ? `**Trigger:** ${d.trigger}` : '',
    d.preconditions?.length ? `**Preconditions:**\n${d.preconditions.map((p: string) => `- ${p}`).join('\n')}` : '',
    '',
    '**Steps:**',
    ...steps,
    '',
    d.outcomes?.length ? `**Outcomes:**\n${d.outcomes.map((o: string) => `- ${o}`).join('\n')}` : '',
    d.postconditions?.length ? `**Postconditions:**\n${d.postconditions.map((o: string) => `- ${o}`).join('\n')}` : '',
    d.openQuestions?.length ? `> **Open questions:**\n${d.openQuestions.map((q: string) => `> - ${q}`).join('\n')}` : '',
    '',
    evidenceBlock(project, j.id),
  ].filter((l) => l !== undefined).join('\n');
}

function renderFeature(project: Project, phase: Phase | undefined, f: Item, children: Item[]) {
  const by = (t: string) => children.filter((c) => c.type === t && visible(c));
  const journeys = by('journey').sort((a, b) => VARIANT_ORDER.indexOf(a.data.variant) - VARIANT_ORDER.indexOf(b.data.variant));
  return [
    `# ${f.title}`,
    phase ? `Phase: **${phase.name}** · ${statusBadge(f)} · id: \`${f.id}\`` : '',
    '',
    f.summary ?? '',
    f.data.actors?.length ? `\n**Actors:** ${f.data.actors.join(', ')}` : '',
    '',
    `## Journeys (${journeys.length})`,
    '',
    '| Journey | Variant | Actor |',
    '|---|---|---|',
    ...journeys.map((j) => `| ${j.title} | ${j.data.variant} | ${j.data.actor} |`),
    '',
    ...journeys.map((j) => renderJourney(project, j)),
    by('rule').length ? `## Business rules\n\n${by('rule').map((r) => `- **${r.title}** — ${r.summary}${r.data.rationale ? ` _(${r.data.rationale})_` : ''}\n${evidenceBlock(project, r.id)}`).join('\n')}` : '',
    by('flow').length ? `## Technical flows\n\n${by('flow').map((fl) => `### ${fl.title}\n\n${fl.summary ?? ''}\n\n\`\`\`mermaid\n${flowMermaid(fl)}\n\`\`\`\n\n${(fl.data.steps ?? []).map((s: any, i: number) => `${i + 1}. \`${s.layer}\` ${s.description}${s.ref ? ` (${s.ref})` : ''}`).join('\n')}\n\n${evidenceBlock(project, fl.id)}`).join('\n')}` : '',
    by('screen').length ? `## Screens\n\n${by('screen').map((s) => `### ${s.title}${s.data.route ? ` (\`${s.data.route}\`)` : ''}\n\n${s.summary ?? ''}\n\n${s.data.elements?.length ? `**Elements:** ${s.data.elements.join('; ')}\n\n` : ''}${s.data.states?.length ? `**States:** ${s.data.states.join('; ')}\n` : ''}`).join('\n')}` : '',
    '',
    `Gherkin: [\`${f.slug}.feature\`](./${f.slug}.feature) · Playwright: [\`e2e/${f.slug}.spec.ts\`](./e2e/${f.slug}.spec.ts)`,
    '',
    evidenceBlock(project, f.id),
  ].join('\n');
}

function entityMermaid(entities: Item[]) {
  const lines = ['classDiagram'];
  for (const e of entities) {
    const name = e.title.replace(/\W+/g, '_');
    lines.push(`  class ${name} {`);
    for (const f of (e.data.fields ?? []).slice(0, 20)) lines.push(`    ${String(f.type).replace(/\W+/g, '_')} ${String(f.name).replace(/\W+/g, '_')}`);
    lines.push('  }');
  }
  return lines.join('\n');
}

function renderEntities(project: Project, entities: Item[]) {
  return entities.map((e) => [
    `### ${e.title}`,
    e.summary ?? '',
    '',
    e.data.fields?.length ? `| Field | Type | Notes |\n|---|---|---|\n${e.data.fields.map((f: any) => `| ${f.name} | ${f.type} | ${f.notes ?? ''} |`).join('\n')}` : '',
    e.data.lifecycle?.length ? `\n**Lifecycle:** ${e.data.lifecycle.join(' → ')}` : '',
    '',
    evidenceBlock(project, e.id),
  ].join('\n')).join('\n');
}

function renderApis(project: Project, apis: Item[]) {
  return apis.map((a) => [
    `### \`${a.title}\``,
    a.summary ?? '',
    a.data.auth ? `\n**Auth:** ${a.data.auth}` : '',
    a.data.request ? `\n**Request:**\n\`\`\`\n${a.data.request}\n\`\`\`` : '',
    a.data.response ? `\n**Response:**\n\`\`\`\n${a.data.response}\n\`\`\`` : '',
    a.data.errors?.length ? `\n**Errors:**\n${a.data.errors.map((e: any) => `- \`${e.status}\` ${e.meaning}`).join('\n')}` : '',
    '',
    evidenceBlock(project, a.id),
  ].join('\n')).join('\n');
}

/** Render every spec item from the DB into Markdown / Gherkin / Playwright files under .code2spec/specs. */
export function renderAll(project: Project, outDir = project.path('specs')) {
  rmSync(outDir, { recursive: true, force: true });
  const phases = listPhases(project).filter((p) => p.status !== 'rejected');
  const all = listItems(project).filter(visible);
  const childrenOf = new Map<string, Item[]>();
  for (const i of all) if (i.parent_id) childrenOf.set(i.parent_id, [...(childrenOf.get(i.parent_id) ?? []), i]);

  const index: string[] = [`# ${project.config.name} — Specification`, '', 'Generated by code2spec from the legacy codebase. Implementation-neutral: describes behaviour, not code.', ''];
  const coverage = computeCoverage(project);
  index.push(`**Coverage:** ${coverage.percent}% of ${coverage.total} code units are referenced by spec evidence. See [system/coverage.md](system/coverage.md).`, '');
  index.push('## Phases', '', '| Phase | Features | Journeys | Status |', '|---|---|---|---|');

  for (const phase of phases) {
    const items = all.filter((i) => i.phase_id === phase.id);
    const features = items.filter((i) => i.type === 'feature');
    const dir = join(outDir, 'phases', phase.slug);
    const journeyCount = items.filter((i) => i.type === 'journey').length;
    index.push(`| [${phase.name}](phases/${phase.slug}/README.md) | ${features.length} | ${journeyCount} | ${phase.status} / ${phase.analysis_status} |`);

    const entities = items.filter((i) => i.type === 'entity');
    const apis = items.filter((i) => i.type === 'api');
    const notes = items.filter((i) => i.type === 'tech_note');
    write(join(dir, 'README.md'), [
      `# Phase: ${phase.name}`, '', phase.description ?? '', '',
      `Review: **${phase.status}** · Analysis: **${phase.analysis_status}** · Files: ${phase.files.length}`, '',
      phase.entry_points.length ? `**Entry points:** ${phase.entry_points.map((e) => `\`${e}\``).join(', ')}\n` : '',
      '## Features', '',
      ...features.map((f) => {
        const js = (childrenOf.get(f.id) ?? []).filter((c) => c.type === 'journey');
        return `- [${f.title}](${f.slug}.md) — ${js.length} journeys: ${js.map((j) => j.title).join('; ')}`;
      }),
      '',
      entities.length ? `## Entities\n\n${renderEntities(project, entities)}` : '',
      apis.length ? `## API contracts\n\n${renderApis(project, apis)}` : '',
      notes.length ? `## Technical notes\n\n${notes.map((n) => `### ${n.title}\n\n${n.summary}\n\n${evidenceBlock(project, n.id)}`).join('\n')}` : '',
      `<details><summary>Files (${phase.files.length})</summary>\n\n${phase.files.map((f) => `- \`${f}\``).join('\n')}\n\n</details>`,
    ].join('\n'));

    for (const f of features) {
      const children = childrenOf.get(f.id) ?? [];
      const journeys = children.filter((c) => c.type === 'journey').sort((a, b) => VARIANT_ORDER.indexOf(a.data.variant) - VARIANT_ORDER.indexOf(b.data.variant));
      write(join(dir, `${f.slug}.md`), renderFeature(project, phase, f, children));
      write(join(dir, `${f.slug}.feature`), renderGherkin(f, journeys));
      write(join(dir, 'e2e', `${f.slug}.spec.ts`), renderPlaywright(f, journeys));
    }
  }

  // system level
  const system = all.filter((i) => i.phase_id === null);
  const sysJourneys = system.filter((i) => i.type === 'system_journey');
  const glossary = system.filter((i) => i.type === 'glossary');
  const model = system.filter((i) => i.type === 'entity');
  const relations = listRelations(project);
  const byId = new Map(all.map((i) => [i.id, i]));

  write(join(outDir, 'system', 'journey-map.md'), [
    '# System journeys & relations', '',
    ...sysJourneys.map((sj) => [
      `## ${sj.title}`, '', `${sj.summary ?? ''} (actor: ${sj.data.actor})`, '',
      '```mermaid', 'flowchart LR',
      ...(sj.data.steps ?? []).map((s: any, i: number) => `  j${i}["${mermaidLabel(byId.get(s.journeyId)?.title ?? s.journeyId)}"]${i ? `\n  j${i - 1} --> j${i}` : ''}`),
      '```', '',
      ...(sj.data.steps ?? []).map((s: any, i: number) => `${i + 1}. ${byId.get(s.journeyId)?.title ?? s.journeyId}${s.note ? ` — ${s.note}` : ''}`),
      '',
    ].join('\n')),
    '## Relations', '',
    '| From | Relation | To | Note |', '|---|---|---|---|',
    ...relations.map((r) => `| ${r.from_title} | ${r.kind} | ${r.to_title} | ${r.note ?? ''} |`),
  ].join('\n'));
  write(join(outDir, 'system', 'glossary.md'), ['# Glossary', '', ...glossary.sort((a, b) => a.title.localeCompare(b.title)).map((g) => `- **${g.title}** — ${g.summary}`)].join('\n'));
  write(join(outDir, 'system', 'domain-model.md'), ['# Domain model', '', model.length ? `\`\`\`mermaid\n${entityMermaid(model)}\n\`\`\`\n` : '_Not synthesized yet._', renderEntities(project, model)].join('\n'));
  write(join(outDir, 'system', 'coverage.md'), [
    '# Coverage', '',
    `${coverage.percent}% (${coverage.covered}/${coverage.total} code units referenced by spec evidence)`, '',
    '| Kind | Covered |', '|---|---|',
    ...Object.entries(coverage.byKind).map(([k, v]) => `| ${k} | ${v.covered}/${v.total} |`), '',
    '## Uncovered units', '',
    ...coverage.uncovered.slice(0, 500).map((u) => `- [${u.kind}] \`${u.file}${u.line ? `:${u.line}` : ''}\` ${u.kind === 'file' ? '' : u.name}`),
  ].join('\n'));

  index.push('', '## System', '', '- [Journey map & relations](system/journey-map.md)', '- [Domain model](system/domain-model.md)', '- [Glossary](system/glossary.md)', '- [Coverage](system/coverage.md)', '');
  write(join(outDir, 'README.md'), index.join('\n'));
}
